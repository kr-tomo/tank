// Enemy mix per stage: heavier types grow with the stage number. Types are interleaved so each
// flashing enemy (4th, 11th, 18th) can be any kind.
export function waveFor(n) {
  let armor = Math.min(8, Math.floor(n / 4)), power = Math.min(8, Math.floor((n + 1) / 3)), fast = Math.min(6, 2 + Math.floor(n / 3));
  if (armor + power + fast > STAGE_ENEMIES - 2) fast = STAGE_ENEMIES - 2 - armor - power;
  const basic = STAGE_ENEMIES - armor - power - fast;
  const queues = [['b', basic], ['f', fast], ['p', power], ['a', armor]];
  let out = '';
  while (out.length < STAGE_ENEMIES) for (const q of queues) if (q[1] > 0 && out.length < STAGE_ENEMIES) { out += q[0]; q[1]--; }
  return out;
}

